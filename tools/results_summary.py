"""Results at a glance, generated from results/battery.csv.

    uv run tools/results_summary.py markdown [--battery results/battery.csv]
    uv run tools/results_summary.py html     [--battery results/battery.csv]
    uv run tools/results_summary.py readme   [--battery ...] [--file README.md]

One row per method, one column per class of the theory (A rigid-body result, B assumed pressure
distribution, C the elastic-foundation model itself): the median error over the scenarios and
engines of the class, and the share of runs within 5 %. The methods of the library run on the three
engines and are pooled over them; a native contact model belongs to one engine and has its own row
(`native` is a different model on each engine and is never pooled). The error has ONE definition
here, the one of the robust comparisons of tools/stats.py, shared by this table and by the ranking
of the site: base variant, an error above 100 % and a run without a value (nan, timeout, failed)
count as 100 %. Nothing here is typed by hand: when battery.csv is absent the output says so.
`readme` rewrites the block of README.md between the markers below.
"""

import argparse
import csv
import math
import re
import statistics
import sys
from html import escape
from pathlib import Path

BEGIN = '<!-- results:begin (generated by tools/results_summary.py; do not edit) -->'
END = '<!-- results:end -->'
ENGINES = ('chrono', 'drake', 'mujoco')
CLASSES = ('A', 'B', 'C')
PASS = '5%'
NATIVES = {  # (engine, contact label of the bench) -> the model's name
    ('drake', 'native'): 'Drake hydroelastic',
    ('drake', 'native-point'): 'Drake point',
    ('chrono', 'native'): 'Chrono SMC',
    ('chrono', 'native-nsc'): 'Chrono NSC',
    ('mujoco', 'native'): 'MuJoCo soft',
    ('mujoco', 'native-default'): 'MuJoCo default',
}


CAP = 1.0  # errors above 100 % and runs without a value (nan, timeout, failed) count as 100 %


def _rows(path):
    path = Path(path)
    if not path.exists():
        return []
    with path.open(newline='') as f:
        return list(csv.DictReader(f))


def _errors(battery):
    """{(engine, contact): {class: [error]}} of the base variant, every error capped at CAP and a
    run without a value at CAP; the last of duplicated rows wins. The one definition of this file."""
    unique = {}
    for r in _rows(battery):
        if r['variant'] != 'base':
            continue
        try:
            e = float(r['error']) if r['status'] == 'ok' else CAP
        except ValueError:
            e = CAP
        unique[(r['engine'], r['contact'], r['scenario'])] = (r['class'], CAP if math.isnan(e) else min(e, CAP))
    out = {}
    for (engine, contact, _), (cls, e) in unique.items():
        out.setdefault((engine, contact), {}).setdefault(cls, []).append(e)
    return out


def table(battery='results/battery.csv'):
    """{method: {class: (median error, share within 5 %, runs)}} over the engines, or None without
    the battery. Class C takes the Winkler-type methods only (the laws and Drake hydroelastic)."""
    cells = {}
    for (engine, contact), by_class in _errors(battery).items():
        if engine not in ENGINES:
            continue
        native = contact.startswith('native')
        method = NATIVES.get((engine, contact), f'{engine} {contact}') if native else contact
        for cls, errors in by_class.items():
            if cls not in CLASSES or (cls == 'C' and native and (engine, contact) != ('drake', 'native')):
                continue
            cells.setdefault(method, {}).setdefault(cls, []).extend(errors)
    if not cells:
        return None
    out = {m: {cls: (statistics.median(es), sum(e <= 0.05 for e in es) / len(es), len(es))
               for cls, es in by_class.items()} for m, by_class in cells.items()}
    order = ['gonthier', 'gonthier-thesis', 'distributed', 'distributed-vertex', 'distributed-centroid', 'pcm']
    natives = list(NATIVES.values())
    names = sorted(out, key=lambda m: (order.index(m) if m in order else 99, natives.index(m) if m in natives else 99, m))
    return {m: out[m] for m in names}


def cell(c):
    if c is None:
        return '—'
    med, share, _ = c
    return f'{med * 100:.1f} % ({share * 100:.0f} %)' if med is not None else '—'


ABSENT = ('Results at a glance are generated from `results/battery.csv`, which is not in this '
          + 'checkout. Run the battery (`scripts/bench.sh`) to produce it.')


def markdown(battery='results/battery.csv'):
    rows = table(battery)
    if rows is None:
        return ABSENT
    intro = ('Median error against the analytic reference (share of runs within 5 %), over every '
             'scenario of the class; the methods of the library over the three engines, each native '
             'model on its own engine. Errors above 100 % and runs without a value (nan, timeout, '
             'failed) count as 100 %, as in the ranking of the site. Class A: rigid-body result; B: assumed pressure distribution; '
             'C: the elastic-foundation model itself (a consistency check: only Winkler-type methods).')
    lines = [intro, '', '| Method | Class A | Class B | Class C |', '|---|---|---|---|']
    for m, by_class in rows.items():
        name = m if m in NATIVES.values() or ' ' in m else f'`{m}`'
        lines.append(f'| {name} | ' + ' | '.join(cell(by_class.get(c)) for c in CLASSES) + ' |')
    return '\n'.join(lines)


def html(battery='results/battery.csv'):
    rows = table(battery)
    if rows is None:
        return f'<p class="absent">{escape(ABSENT.replace("`", ""))}</p>'
    head = ''.join(f'<th scope="col" class="num">Class {c}</th>' for c in CLASSES)
    body = ''.join(
        f'<tr><th scope="row">{escape(m) if " " in m else "<code>" + escape(m) + "</code>"}</th>'
        + ''.join(f'<td class="num">{escape(cell(by_class.get(c)))}</td>' for c in CLASSES) + '</tr>'
        for m, by_class in rows.items())
    return (f'<table><thead><tr><th scope="col">Method</th>{head}</tr></thead><tbody>{body}</tbody></table>'
            '<p class="note">Median error against the analytic reference, and in brackets the share of runs '
            'within 5 %, over every scenario of the class and the three engines. Errors above 100 % and failed runs '
            'count as 100 %, as in the ranking.</p>')


# ---- overall ranking (the landing page's "which one should I use") ----
LAWS = {'distributed': 'Distributed law', 'gonthier': 'Gonthier law',
        'gonthier-thesis': 'Gonthier law (2018 thesis variant)', 'pcm': 'PCM baseline'}


def _model(engine, contact):
    """(name, is it one of the library's laws) of a contender, or None for the variants left out."""
    if contact in LAWS:
        return LAWS[contact], True
    if (engine, contact) in NATIVES:
        return NATIVES[(engine, contact)], False
    return None


def ranking(battery, timing):
    """One entry per engine and contact model, most accurate first.

    Accuracy: base variant, classes A and B (class C tests the foundation model itself), error capped
    at 100 % with failed runs at the cap: share of scenarios within 5 % and median error. Speed:
    simulated time over wall time from the timing pass, median over repeats, then over scenarios.
    """
    ratios = {}
    errors = {k: {c: v for c, v in by_class.items() if c in ('A', 'B')}
              for k, by_class in _errors(battery).items() if _model(*k) is not None}
    errors = {k: v for k, v in errors.items() if v}
    for r in _rows(timing):
        if _model(r['engine'], r['contact']) is None or r['status'] != 'ok':
            continue
        try:
            ratios.setdefault((r['engine'], r['contact']), {}).setdefault(r['scenario'], []).append(float(r['realtime_ratio']))
        except ValueError:
            pass
    out = []
    for (engine, contact), by_class in errors.items():
        name, ours = _model(engine, contact)
        both = by_class.get('A', []) + by_class.get('B', [])
        per_scenario = [statistics.median(v) for v in ratios.get((engine, contact), {}).values()]
        out.append({
            'engine': engine, 'contact': contact, 'name': name, 'ours': ours, 'n': len(both),
            'within': sum(e <= 0.05 for e in both) / len(both), 'median': statistics.median(both),
            'median_A': statistics.median(by_class['A']) if by_class.get('A') else None,
            'median_B': statistics.median(by_class['B']) if by_class.get('B') else None,
            'speed': 1.0 / statistics.median(per_scenario) if per_scenario else None,
        })
    out.sort(key=lambda r: (-r['within'], r['median'], r['name'], r['engine']))
    return out


BALANCE = 0.6  # best balance: the fastest model with at least this share of the scenarios within 5 %


def balance(rows):
    """The rows with the best balance: the fastest among those with at least BALANCE of the scenarios
    within 5 %, and the rows tied with it (same share, same speed as the table prints it)."""
    able = [r for r in rows if r['speed'] is not None and r['within'] >= BALANCE]
    if not able:
        return []
    top = max(able, key=lambda r: (r['speed'], r['within']))
    return [r for r in able if r['within'] == top['within'] and _speed(r['speed']) == _speed(top['speed'])]


ENGINE_NAMES = {'drake': 'Drake', 'chrono': 'Chrono', 'mujoco': 'MuJoCo'}


def _who(r, rows, key):
    """A native model by its name; a law of the library with its engine only if the engines differ."""
    if not r['ours']:
        return r['name']
    same = [o[key] for o in rows if o['name'] == r['name'] and o[key] is not None]
    if key != 'speed' and max(same) - min(same) <= 0.05 * max(max(same), 1e-12):
        return f"{r['name']} of this library (on any of the engines)"
    return f"{r['name']} of this library on {ENGINE_NAMES.get(r['engine'], r['engine'])}"


def _speed(v):
    if v is None:
        return '—'
    return f'×{v:.0f}' if v >= 10 else f'×{v:.2g}'


def _head(label, sub, tip):
    return (f'<th scope="col" class="num" title="{escape(tip, quote=True)}">{escape(label)}'
            f'<span class="sub">{escape(sub)}</span></th>')


def ranking_html(battery='results/battery.csv', timing='results/timing.csv'):
    rows = ranking(battery, timing)
    if not rows:
        return '<p class="absent">The ranking is generated from results/battery.csv and results/timing.csv, which are not in this checkout.</p>'
    timed = [r for r in rows if r['speed'] is not None]
    best = rows[0]
    fastest = max(timed, key=lambda r: r['speed']) if timed else None
    best_a = min((r for r in rows if r['median_A'] is not None), key=lambda r: r['median_A'])
    best_b = min((r for r in rows if r['median_B'] is not None), key=lambda r: r['median_B'])

    def pct(v):
        return f'{v * 100:.2g} %'

    picks = [
        ('Bodies touching over an area (a shaft in a bearing, a disk spinning on a face)',
         f'{_who(best_b, rows, "median_B")}: median error {pct(best_b["median_B"])} on the class B scenarios.'),
        ('Sliding, rolling and stacking of rigid bodies',
         f'{_who(best_a, rows, "median_A")}: median error {pct(best_a["median_A"])} on the class A scenarios.'),
        ('Most accurate overall',
         f'{_who(best, rows, "median")}: {best["within"] * 100:.0f} % of the class A and B scenarios within 5 % of the theory.'),
    ]
    if fastest:
        picks.append(('Fastest overall',
                      (f'{_who(fastest, rows, "speed")}: {_speed(fastest["speed"])} real time (median), with '
                       f'{fastest["within"] * 100:.0f} % of the scenarios within 5 %.')))
    balanced = balance(rows)
    if balanced:
        top = balanced[0]
        names = list(dict.fromkeys(r['name'] for r in balanced))
        if len(names) == 1 and top['ours']:
            engines = ' and '.join(ENGINE_NAMES.get(r['engine'], r['engine']) for r in balanced)
            who = f"{top['name']} of this library on {engines}"
        else:
            who = ' and '.join(names)
        picks.append(('Best balance',
                      (f'{who}: {_speed(top["speed"])} real time (median), the fastest with at least '
                       f'{BALANCE * 100:.0f} % of the scenarios within 5 % ({top["within"] * 100:.0f} %).')))
    cards = ''.join(f'<li><b>{escape(k)}</b><span>{escape(v)}</span></li>' for k, v in picks)
    body = ''
    for i, r in enumerate(rows, 1):
        marks = ''.join(f'<i class="mark">{m}</i>' for m, on in (
            ('most accurate', r['within'] == best['within'] and r['median'] <= 1.05 * best['median']),
            ('fastest', r is fastest), ('best balance', any(r is o for o in balanced))) if on)
        body += (f'<tr><td class="num">{i}</td><th scope="row">{escape(r["name"])}{marks}</th>'
                 f'<td>{escape(ENGINE_NAMES.get(r["engine"], r["engine"]))}</td>'
                 f'<td class="num">{r["within"] * 100:.0f} %</td><td class="num">{pct(r["median"])}</td>'
                 f'<td class="num">{_speed(r["speed"])}</td></tr>')
    n = rows[0]['n']
    return (f'<ul class="picks">{cards}</ul>'
            '<table class="ranking"><thead><tr><th scope="col" class="num">#</th><th scope="col">Contact model</th>'
            '<th scope="col">Engine</th>'
            f'{_head("Scenarios within 5 % error", "share, higher is better", f"Share of the {n} class A and B scenarios whose error against the analytic theory is at most 5 %. Higher is better.")}'
            f'{_head("Median error", "vs theory, lower is better", "Median over the same scenarios of the error against the analytic theory. Lower is better.")}'
            f'{_head("Speed", "× real time, higher is better", "Simulated time divided by computing time, median over the scenarios: ×100 runs a hundred times faster than real time, ×0.5 at half of real-time speed. Higher is better.")}'
            '</tr></thead>'
            f'<tbody>{body}</tbody></table>'
            f'<p class="note">Ranked by the share of the {n} class A and B scenarios within 5 % error, then by the '
            'median error (base meshes, 1 ms step; errors above 100 % and failed runs count as 100 %). Speed is measured on '
            f'one machine. Best balance: the fastest model with at least {BALANCE * 100:.0f} % of the scenarios within 5 %. The four '
            'laws of this library run on any of the engines; each native model is its engine\'s own contact, configured by '
            'us with one documented rule. <strong>Read the ranking with care</strong>: in the paper\'s robust analysis most differences '
            'between the laws and the native models on class A are not statistically significant, and class C (the '
            'foundation model tested against itself) is left out here.</p>')


def readme(battery, file):
    text = Path(file).read_text()
    block = f'{BEGIN}\n{markdown(battery)}\n{END}'
    pattern = re.compile(re.escape(BEGIN) + r'.*?' + re.escape(END), re.DOTALL)
    if not pattern.search(text):
        sys.exit(f'results_summary: no results markers in {file}')
    Path(file).write_text(pattern.sub(lambda _: block, text))


def main():
    p = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    p.add_argument('mode', choices=['markdown', 'html', 'readme'])
    p.add_argument('--battery', default='results/battery.csv')
    p.add_argument('--file', default='README.md')
    a = p.parse_args()
    if a.mode == 'readme':
        readme(a.battery, a.file)
    else:
        print(markdown(a.battery) if a.mode == 'markdown' else html(a.battery))


if __name__ == '__main__':
    main()
